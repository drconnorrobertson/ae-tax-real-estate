'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const sandbox={module:{exports:{}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../public/assets/rental-operating-calculators.js'),'utf8'),sandbox);
const c=sandbox.module.exports;
const close=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-7,`${actual} != ${expected}`);
close(c.rent_steps({rent:1500,rate:3,years:3})[1][1],55636.2);
close(c.rent_steps({rent:1500,rate:0,years:3})[2][1],0);
close(c.rent_steps({rent:1500,rate:3,years:1})[0][1],1500);
assert.throws(()=>c.rent_steps({rent:1,rate:3,years:1.5}),/whole/);
assert.throws(()=>c.rent_steps({rent:1,rate:101,years:2}),/100/);
close(c.leasing_fee({rent:1500,months:12,rate:5,flat:100})[2][1],1000);
close(c.leasing_fee({rent:0,months:1,rate:0,flat:100})[3][1],100);
assert.throws(()=>c.leasing_fee({rent:1,months:0,rate:0,flat:0}),/months/);
close(c.turnover_hours({units:4,perUnit:6,travel:4,available:20})[0][1],28);
assert.equal(c.turnover_hours({units:4,perUnit:6,travel:4,available:20})[2][1],2);
assert.equal(c.turnover_hours({units:0,perUnit:6,travel:0,available:20})[2][1],0);
assert.throws(()=>c.turnover_hours({units:1,perUnit:6,travel:0,available:0}),/positive/);
close(c.project_allowance({base:20000,alternates:1500,allowances:2000,rate:10})[2][1],25850);
close(c.project_allowance({base:20000,alternates:0,allowances:0,rate:0})[2][1],20000);
assert.throws(()=>c.project_allowance({base:1,alternates:0,allowances:0,rate:101}),/100/);
close(c.unpaid_bills({opening:4000,newBills:9000,credits:500,paid:8000})[2][1],4500);
close(c.unpaid_bills({opening:0,newBills:10,credits:10,paid:0})[2][1],0);
assert.throws(()=>c.unpaid_bills({opening:0,newBills:10,credits:2,paid:9}),/exceed/);
const cash={opening:10000,receipt1:5000,cost1:7000,receipt2:0,cost2:12000,receipt3:15000,cost3:5000};
assert.equal(c.milestone_cash(cash)[3][1],-4000);
assert.equal(c.milestone_cash(cash)[4][1],4000);
assert.equal(c.milestone_cash({...cash,opening:14000})[4][1],0);
console.log('Six rental operating calculators: worked examples, zero cases and invalid boundaries pass');
