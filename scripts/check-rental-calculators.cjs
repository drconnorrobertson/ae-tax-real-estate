const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const sandbox={module:{exports:{}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../public/assets/rental-decision-calculators.js'),'utf8'),sandbox);
const c=sandbox.module.exports;
assert.equal(c.vacancy({oldRent:1500,newRent:1600,vacancy:1,turnover:500})[2][1],20);
assert.throws(()=>c.vacancy({oldRent:1500,newRent:1500,vacancy:1,turnover:0}),/above current/);
assert.equal(c.concession({rent:1800,months:12,credit:1800})[2][1],1650);
assert.throws(()=>c.concession({rent:100,months:1,credit:101}),/cannot exceed/);
assert.equal(c.management({rent:5000,collection:90,rate:8,flat:350})[3][1],120);
assert.equal(c.reserve({cost:12000,saved:3000,months:18})[1][1],500);
assert.equal(c.reserve({cost:500,saved:600,months:12})[0][1],0);
assert.equal(c.reserve({cost:500,saved:600,months:12})[2][1],100);
assert.equal(c.utilities({budget:200,actual:250})[1][1],25);
assert.equal(c.utilities({budget:200,actual:150})[0][1],-50);
assert.equal(c.replacement({replace:5000,repair:1000,savings:500})[2][1],8);
assert.equal(c.replacement({replace:800,repair:1000,savings:500})[2][1],0);
assert.equal(c.vendor({contract:1200,visit:100,visits:10,extras:100})[3][1],11);
assert.equal(c.vendor({contract:1201,visit:100,visits:10,extras:100})[3][1],12);
assert.equal(c.vendor({contract:100,visit:50,visits:1,extras:150})[3][1],0);
assert.equal(c.software({monthly:20,setup:120,hours:2,hourValue:30})[3][1],360);
console.log('Rental calculators: eight models and boundary cases passed');
